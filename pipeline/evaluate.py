"""Retrieval quality on the 37 official test questions of mariadb-vector-wikipedia-rag (data/eval/test-questions.tsv).

    uv run python -m pipeline.evaluate

Same metric as the starter's evaluate.py: a hit is the expected topic in ANY language (same wikidata_id,
or the Finnish page) within the top k topics. Compared:
- baseline   one vector per article (the starter's design, its ready-made vectors) — should reproduce 76% / 86%
- vector     our passage vectors (122,351 passages)
- keyword    stemmed FULLTEXT over passages
- hybrid     both, fused with RRF in one SQL statement
Writes perf/EVAL.md.
"""
from __future__ import annotations

import csv
import statistics

from backend import db, search
from backend.embed import embed
from pipeline.common import ROOT, connect

BASELINE_SQL = """
SELECT a.lang, a.page_id, a.wikidata_id, v.d
FROM (SELECT lang, page_id, VEC_DISTANCE_COSINE(embedding, VEC_FromText(%s)) AS d
      FROM article_vector ORDER BY d LIMIT 10) v
JOIN article a USING (lang, page_id)
ORDER BY v.d"""


def rank_of(topics: list[tuple[str | None, str, int]], q: dict) -> int | None:
    for i, (qid, lang, page_id) in enumerate(topics[:10], 1):
        if (q["wikidata_id"] and qid == q["wikidata_id"]) or (lang == "fi" and page_id == q["page_id"]):
            return i
    return None


def summary(ranks: list[int | None]) -> dict:
    hit = lambda k: sum(1 for r in ranks if r and r <= k) / len(ranks)
    return {"hit1": hit(1), "hit5": hit(5), "hit10": hit(10),
            "mrr": statistics.mean(1 / r if r else 0 for r in ranks)}


def main() -> None:
    con = connect()
    cur = con.cursor()
    with open(ROOT / "data" / "eval" / "test-questions.tsv", encoding="utf-8") as f:
        questions = list(csv.DictReader(f, delimiter="\t"))
    for q in questions:
        cur.execute("SELECT wikidata_id, page_id FROM article WHERE lang = 'fi' AND title = %s", (q["expected_fi_title"],))
        row = cur.fetchone()
        q["wikidata_id"], q["page_id"] = (row["wikidata_id"], row["page_id"]) if row else (None, None)
    missing = [q["expected_fi_title"] for q in questions if q["page_id"] is None]
    if missing:
        print("expected articles not found:", missing)

    # Baseline: whole-article vectors, embedded exactly like dataset S (8,192 tokens; a question is short).
    vecs = embed([q["question"] for q in questions], batch_size=16, max_length=512)
    ranks = {"baseline": [], "vector": [], "keyword": [], "hybrid": []}
    misses = {k: [] for k in ranks}
    for q, v in zip(questions, vecs):
        cur.execute(BASELINE_SQL, (db.vec_literal(v),))
        seen, topics = set(), []
        for r in cur.fetchall():
            key = r["wikidata_id"] or f"{r['lang']}:{r['page_id']}"
            if key not in seen:
                seen.add(key)
                topics.append((r["wikidata_id"], r["lang"], r["page_id"]))
        ranks["baseline"].append(rank_of(topics, q))
        for mode in ("vector", "keyword", "hybrid"):
            res = search.search(q["question"], mode, None, limit=60)
            topics = [(g["wikidata_id"], g["best"]["lang"], g["best"]["page_id"]) for g in res.groups]
            # a topic group may hold the Finnish page under another language's best passage
            topics = [(qid, "fi" if g["by_lang"].get("fi") else l, g["by_lang"]["fi"]["page_id"] if g["by_lang"].get("fi") else pid)
                      for (qid, l, pid), g in zip(topics, res.groups)]
            r = rank_of(topics, q)
            ranks[mode].append(r)
            if not r or r > 5:
                misses[mode].append(f"[{q['lang']}] {q['question']} → {q['expected_fi_title']}")

    names = {"baseline": "one vector per article (starter design)", "vector": "passage vectors",
             "keyword": "stemmed FULLTEXT passages", "hybrid": "hybrid, weighted RRF (vector 1.0 + FULLTEXT 0.35)"}
    lines = ["# Retrieval quality — 37 official test questions", "",
             "Questions and metric from `mariadb-vector-wikipedia-rag` (13 en, 11 sv, 13 fi). A hit = the expected topic "
             "in any language within the top k topics. Generated by `pipeline/evaluate.py`.", "",
             "| Method | hit@1 | hit@5 | hit@10 | MRR |", "|---|---|---|---|---|"]
    for k, rs in ranks.items():
        s = summary(rs)
        lines.append(f"| {names[k]} | {s['hit1']:.0%} | {s['hit5']:.0%} | {s['hit10']:.0%} | {s['mrr']:.2f} |")
    for lang in ("en", "sv", "fi"):
        idx = [i for i, q in enumerate(questions) if q["lang"] == lang]
        s = summary([ranks["hybrid"][i] for i in idx])
        lines.append(f"| ↳ hybrid, questions in {lang} ({len(idx)}) | {s['hit1']:.0%} | {s['hit5']:.0%} | {s['hit10']:.0%} | {s['mrr']:.2f} |")
    lines += ["", "Hybrid misses (not in top 5):", ""] + [f"- {m}" for m in misses["hybrid"]]
    (ROOT / "perf").mkdir(exist_ok=True)
    (ROOT / "perf" / "EVAL.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
